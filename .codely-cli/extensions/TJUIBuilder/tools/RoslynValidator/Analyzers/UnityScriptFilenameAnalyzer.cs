using System;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace RoslynValidator.Analyzers
{
    /// <summary>UR039: concrete public Unity object scripts must match their filename.</summary>
    [DiagnosticAnalyzer(LanguageNames.CSharp)]
    public sealed class UnityScriptFilenameAnalyzer : DiagnosticAnalyzer
    {
        public static readonly DiagnosticDescriptor UR039 = new(
            "UR039",
            "Unity script filename mismatch",
            "Public concrete {0} '{1}' must be declared in '{1}.cs', not '{2}'",
            "Correctness",
            DiagnosticSeverity.Error,
            isEnabledByDefault: true);

        public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics =>
            ImmutableArray.Create(UR039);

        public override void Initialize(AnalysisContext context)
        {
            context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.None);
            context.EnableConcurrentExecution();
            context.RegisterSyntaxNodeAction(AnalyzeClass, SyntaxKind.ClassDeclaration);
        }

        private static void AnalyzeClass(SyntaxNodeAnalysisContext context)
        {
            var declaration = (ClassDeclarationSyntax)context.Node;
            if (declaration.Parent is TypeDeclarationSyntax) return;
            if (declaration.Modifiers.Any(SyntaxKind.PartialKeyword) || IsGenerated(declaration.SyntaxTree)) return;

            var symbol = context.SemanticModel.GetDeclaredSymbol(declaration);
            if (symbol == null || symbol.DeclaredAccessibility != Accessibility.Public || symbol.IsAbstract ||
                symbol.Arity != 0 || !IsUnityScript(symbol, context.Compilation, out var kind)) return;

            var actualName = Path.GetFileNameWithoutExtension(declaration.SyntaxTree.FilePath);
            if (string.Equals(actualName, symbol.Name, StringComparison.Ordinal)) return;
            context.ReportDiagnostic(Diagnostic.Create(
                UR039, declaration.Identifier.GetLocation(), kind, symbol.Name,
                Path.GetFileName(declaration.SyntaxTree.FilePath)));
        }

        private static bool IsUnityScript(INamedTypeSymbol symbol, Compilation compilation, out string kind)
        {
            var mono = compilation.GetTypeByMetadataName("UnityEngine.MonoBehaviour");
            var scriptable = compilation.GetTypeByMetadataName("UnityEngine.ScriptableObject");
            for (var current = symbol.BaseType; current != null; current = current.BaseType)
            {
                if (mono != null && SymbolEqualityComparer.Default.Equals(current, mono))
                {
                    kind = "MonoBehaviour";
                    return true;
                }
                if (scriptable != null && SymbolEqualityComparer.Default.Equals(current, scriptable))
                {
                    kind = "ScriptableObject";
                    return true;
                }
            }
            kind = string.Empty;
            return false;
        }

        private static bool IsGenerated(SyntaxTree tree)
        {
            var file = Path.GetFileName(tree.FilePath);
            if (file.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) ||
                file.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase) ||
                file.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase)) return true;
            var text = tree.GetText();
            var prefix = text.ToString(TextSpan.FromBounds(0, Math.Min(text.Length, 512)));
            return prefix.IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0;
        }
    }
}
